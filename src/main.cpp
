#include <iostream>
#include "PhoneBook.h"

int main() {
    PhoneBook myPhoneBook;
    int choice;

    do {
        std::cout << "\n=========================\n";
        std::cout << "    PHONEBOOK SYSTEM     \n";
        std::cout << "=========================\n";
        std::cout << "1. Add Contact\n";
        std::cout << "2. View All Contacts\n";
        std::cout << "3. Search Contact\n";
        std::cout << "4. Delete Contact\n";
        std::cout << "5. Exit\n";
        std::cout << "Enter your choice (1-5): ";
        std::cin >> choice;

        switch (choice) {
            case 1:
                myPhoneBook.addContact();
                break;
            case 2:
                myPhoneBook.displayAllContacts();
                break;
            case 3:
                myPhoneBook.searchContact();
                break;
            case 4:
                myPhoneBook.deleteContact();
                break;
            case 5:
                std::cout << "Exiting application. Goodbye!\n";
                break;
            default:
                std::cout << "❌ Invalid choice. Please try again.\n";
        }
    } while (choice != 5);

    return 0;
}
